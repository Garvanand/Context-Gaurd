def build_and_save_dataset():
    data_dir = Path("benchmark/data")
    data_dir.mkdir(parents=True, exist_ok=True)

    raw_pairs = get_all_60_earb_pairs()
    print(f"Loaded {len(raw_pairs)} candidate EARB pairs.")

    # 1. Pydantic validation
    validated_pairs: List[EARBPair] = []
    base_artifact_ids = set()
    category_counts = {}
    split_counts = {"dev": 0, "test": 0}

    for idx, item in enumerate(raw_pairs):
        try:
            pair = EARBPair(**item)
            validated_pairs.append(pair)
            base_artifact_ids.add(pair.base_artifact_id)
            cat_val = pair.category.value
            category_counts[cat_val] = category_counts.get(cat_val, 0) + 1
            split_counts[pair.split] = split_counts.get(pair.split, 0) + 1
        except Exception as e:
            print(f"ValidationError at item {idx} ({item.get('pair_id')}): {e}")
            raise e

    print(f"Validated all {len(validated_pairs)} pairs successfully!")
    print(f"Total Base Artifacts: {len(base_artifact_ids)}")
    print(f"Category counts: {category_counts}")
    print(f"Split counts: {split_counts}")

    # 2. Strict Leakage Verification
    artifact_splits = {}
    for p in validated_pairs:
        if p.base_artifact_id not in artifact_splits:
            artifact_splits[p.base_artifact_id] = p.split
        else:
            assert artifact_splits[p.base_artifact_id] == p.split, (
                f"LEAKAGE DETECTED: Artifact {p.base_artifact_id} spans multiple splits!"
            )
    print("Leakage verification passed: 100% split purity across all base artifacts.")

    # 3. Export JSONL
    jsonl_path = data_dir / "earb_v1.jsonl"
    with open(jsonl_path, "w", encoding="utf-8") as f:
        for p in validated_pairs:
            # Dump as dictionary with serialized enum values
            p_dict = p.model_dump()
            p_dict["category"] = p.category.value
            p_dict["severity"] = p.severity.value
            p_dict["reversibility"] = p.reversibility.value
            p_dict["expected_intervention"] = p.expected_intervention.value
            f.write(json.dumps(p_dict, ensure_ascii=False) + "\n")
    print(f"Exported JSONL: {jsonl_path} ({jsonl_path.stat().st_size} bytes, {len(validated_pairs)} lines)")

    # 4. Export CSV
    csv_path = data_dir / "earb_v1.csv"
    csv_fields = [
        "pair_id", "base_artifact_id", "artifact_type", "artifact_path", "category",
        "context", "source_app", "recipient", "destination", "intended_action",
        "risk_type", "risk_subtype", "severity", "reversibility", "uncertainty",
        "expected_intervention", "acceptable_alternative", "is_negative_control",
        "is_ambiguous", "split", "evidence", "rationale"
    ]
    with open(csv_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=csv_fields)
        writer.writeheader()
        for p in validated_pairs:
            row = p.model_dump()
            row["category"] = p.category.value
            row["severity"] = p.severity.value
            row["reversibility"] = p.reversibility.value
            row["expected_intervention"] = p.expected_intervention.value
            row["evidence"] = " | ".join(p.evidence)
            row["acceptable_alternative"] = p.acceptable_alternative or ""
            writer.writerow({k: row.get(k, "") for k in csv_fields})
    print(f"Exported CSV: {csv_path} ({csv_path.stat().st_size} bytes)")


if __name__ == "__main__":
    build_and_save_dataset()
